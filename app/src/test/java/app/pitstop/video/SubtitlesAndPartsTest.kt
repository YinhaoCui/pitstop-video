class BiliSubtitlesTest {
    @Test fun convertsJsonToVtt() {
        val json = """{"body":[
            {"from":0.5,"to":2.25,"content":"你好"},
            {"from":3,"to":3,"content":"zero length dropped"},
            {"from":3661.007,"to":3662,"content":"a --> b\n\nc"}
        ]}"""
        assertEquals(
            "WEBVTT\n\n00:00:00.500 --> 00:00:02.250\n你好\n\n01:01:01.007 --> 01:01:02.000\na -> b\nc\n\n",
            BiliSubtitles.jsonToVtt(json),
        )
    }

    @Test fun emptyBody() = assertEquals("WEBVTT\n\n", BiliSubtitles.jsonToVtt("{}"))

    @Test fun languageAndPartTitles() {
        assertEquals("zh", BiliSubtitles.language("ai-zh"))
        assertEquals("zh-CN", BiliSubtitles.language("zh-CN"))
        assertEquals("Trip · P2 Day two", BiliSubtitles.partTitle("Trip", 2, "Day two"))
        assertEquals("Trip · P1", BiliSubtitles.partTitle("Trip", 1, "Trip"))
        assertEquals("Trip · P3", BiliSubtitles.partTitle("Trip", 3, " "))
    }
}

class YouTubeSubtitlesTest {
    private val en = Candidate("https://yt/tt?lang=en&fmt=vtt", "en", "English", auto = false)
    private val ja = Candidate("https://yt/tt?lang=ja&fmt=vtt", "ja", "Japanese", auto = false)
    private val enAuto = Candidate("https://yt/tt?lang=en&kind=asr", "en", "English", auto = true)
    private val deAuto = Candidate("https://yt/tt?lang=de&kind=asr", "de", "German", auto = true)

    @Test fun keepsManualAndOwnLanguageAutoOnly() {
        val picked = YouTubeSubtitles.pick(listOf(ja, en, enAuto, deAuto), "en")
        assertEquals(listOf("English", "Japanese", "English (auto)"), picked.map { it.label })
    }

    @Test fun addsTranslationWhenViewerLanguageMissing() {
        val picked = YouTubeSubtitles.pick(listOf(en, deAuto), "zh")
        assertEquals("https://yt/tt?lang=en&fmt=vtt&tlang=zh", picked.last().uri)
        assertTrue(picked.last().autoGenerated)
        assertTrue(picked.last().label.endsWith("(auto-translated)"))
    }

    @Test fun nothingAvailable() = assertTrue(YouTubeSubtitles.pick(emptyList(), "zh").isEmpty())
}

class DeviceAwareSelectionTest {
    @Test fun dropsTracksTheDeviceCannotDecode() {
        val tracks = listOf(VideoTrack("av1-1080", 1080, "av01"), VideoTrack("avc-720", 720, "avc1"))
        assertEquals("av1-1080", StreamSelector.pickVideo(tracks, supported = { true })!!.url)
        assertEquals("avc-720", StreamSelector.pickVideo(tracks, supported = { it.codec.startsWith("avc") })!!.url)
        // If nothing is known to be decodable, still try something rather than nothing.
        assertEquals("av1-1080", StreamSelector.pickVideo(tracks, supported = { false })!!.url)
    }

    @Test fun safeQualityCap() =
        assertEquals("avc-480", StreamSelector.pickVideo(
            listOf(VideoTrack("avc-1080", 1080, "avc1"), VideoTrack("avc-480", 480, "avc1")), maxHeight = 480,
        )!!.url)
}

class PlaylistPartsTest {
    private val p1 = VideoItem(SourceId.BILIBILI, "BV1", "T · P1", extra = "11", part = 1)
    private val p2 = p1.copy(title = "T · P2", extra = "12", part = 2)

    @Test fun partsOfOneVideoAreDistinct() {
        val pl = PlaylistOps.add(PlaylistOps.add(Playlist("x", "x"), p1), p2)
        assertEquals(2, pl.items.size)
        assertTrue(PlaylistOps.contains(pl, p2))
        assertFalse(PlaylistOps.contains(pl, p1.copy(part = null)))
    }

    @Test fun partSurvivesJson() {
        val list = listOf(Playlist("x", "x", listOf(p1, p2)))
        assertEquals(list, PlaylistOps.fromJson(PlaylistOps.toJson(list)))
    }
}
