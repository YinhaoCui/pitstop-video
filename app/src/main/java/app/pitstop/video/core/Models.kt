package app.pitstop.video.core

/** Every feed the app can play. [music] sources are audio-only: no picture, so no parked-only lock. */
enum class SourceId(val music: Boolean = false) {
    YOUTUBE, BILIBILI, LOCAL,
    BILI_MUSIC(true), YT_MUSIC(true), NETEASE(true), GDRIVE(true), LOCAL_MUSIC(true),
}

/** Items whose id starts with this are collections (playlist / folder); [VideoSource.expand] turns them into tracks. */
const val COLLECTION_PREFIX = "list:"

/** One playable video as listed by a source. [id] is whatever the source needs to resolve it. */
data class VideoItem(
    val source: SourceId,
    val id: String,
    val title: String,
    val author: String? = null,
    val thumbnailUrl: String? = null,
    val durationSec: Long? = null,
    /** Source-specific extra (e.g. Bilibili cid). */
    val extra: String? = null,
    /** Part number of a multi-part video (Bilibili 分P); null for a whole video. */
    val part: Int? = null,
    /** The creator's id in this source (YouTube channel URL, Bilibili mid), for "more from this creator". */
    val authorId: String? = null,
)

/** A sideloaded subtitle track (WebVTT). */
data class SubtitleTrack(
    val uri: String,
    /** BCP-47 tag, e.g. "en", "zh-Hans". */
    val language: String,
    val label: String,
    val autoGenerated: Boolean = false,
)

/** A browsable list inside a source ("Popular", "Subscriptions", ...). */
data class Feed(val key: String, val title: String)

/** Where the player should actually fetch media from. */
data class PlayableStream(
    val videoUri: String,
    /** Separate audio track (YouTube / Bilibili DASH split streams), merged at playback. */
    val audioUri: String? = null,
    val headers: Map<String, String> = emptyMap(),
    val kind: Kind = Kind.PROGRESSIVE,
    val subtitles: List<SubtitleTrack> = emptyList(),
) {
    enum class Kind { PROGRESSIVE, HLS, DASH }
}

interface VideoSource {
    val id: SourceId
    val displayName: String
    val supportsSearch: Boolean get() = true

    /** Feeds available right now (login-only feeds disappear when signed out). */
    fun feeds(): List<Feed>
    suspend fun load(feed: Feed): List<VideoItem>
    suspend fun search(query: String): List<VideoItem>
    suspend fun resolve(item: VideoItem): PlayableStream

    /** Splits a multi-part video into its parts (Bilibili 分P); null when it is a single video. */
    suspend fun expand(item: VideoItem): List<VideoItem>? = null

    /** True for rows that open like a folder (subfolders + tracks) instead of playing. */
    fun isFolder(item: VideoItem): Boolean = false

    /** Contents of a folder row: subfolders first, then playable items. */
    suspend fun browse(item: VideoItem): List<VideoItem> = emptyList()

    /** True when [creatorVideos] works (items then carry [VideoItem.authorId]). */
    val supportsCreators: Boolean get() = false

    /** Latest videos of one creator (channel / uploader). */
    suspend fun creatorVideos(authorId: String): List<VideoItem> = emptyList()
}

/**
 * Every playable track inside a folder row, subfolders included (breadth-first), at most [limit].
 * A non-folder item is returned as itself.
 */
suspend fun VideoSource.folderTracks(item: VideoItem, limit: Int = 1000): List<VideoItem> {
    if (!isFolder(item)) return listOf(item)
    val out = mutableListOf<VideoItem>()
    val pending = ArrayDeque(listOf(item))
    val seen = mutableSetOf(item.id)
    while (pending.isNotEmpty() && out.size < limit) {
        for (child in browse(pending.removeFirst())) {
            if (isFolder(child)) { if (seen.add(child.id)) pending += child }
            else if (out.size < limit) out += child
        }
    }
    return out
}

/**
 * Global stream-quality policy. [safe] is switched on for one retry after a decoder failure
 * (older phones, emulators, cheap head units): AVC only, at most 480p.
 */
object StreamPolicy {
    @Volatile var safe: Boolean = false
    /** Lowered step by step when the connection keeps stalling; reset when the network changes. */
    @Volatile var capHeight: Int = 1080
    val maxHeight: Int get() = if (safe) minOf(480, capHeight) else capHeight
}

/** Thrown for problems the user can fix (sign in, grant permission...). Message is shown as-is. */
class UserFacingException(message: String) : Exception(message)

fun formatDuration(sec: Long?): String {
    if (sec == null || sec <= 0) return ""
    val h = sec / 3600
    val m = (sec % 3600) / 60
    val s = sec % 60
    return if (h > 0) "%d:%02d:%02d".format(h, m, s) else "%d:%02d".format(m, s)
}

/** Parses "m:ss" or "h:mm:ss". */
fun parseClock(text: String?): Long? {
    if (text.isNullOrBlank()) return null
    val parts = text.trim().split(":").map { it.toLongOrNull() ?: return null }
    return parts.fold(0L) { acc, p -> acc * 60 + p }
}

/** Parses ISO-8601 durations as used by the YouTube Data API, e.g. "PT1H2M3S". */
fun parseIsoDuration(text: String?): Long? {
    if (text.isNullOrBlank()) return null
    val m = Regex("""^P(?:(\d+)D)?(?:T(?:(\d+)H)?(?:(\d+)M)?(?:(\d+)S)?)?$""").matchEntire(text) ?: return null
    val (d, h, min, s) = m.destructured
    fun n(v: String) = v.toLongOrNull() ?: 0L
    return n(d) * 86400 + n(h) * 3600 + n(min) * 60 + n(s)
}
